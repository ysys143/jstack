export function normalizeModelName(model: string): string { return model.replace(/^(openai|anthropic|google|alibaba|moonshot|deepseek|zhipu|upstage):/i, '').replace(/^(gpt|claude|gemini|qwen|kimi|deepseek|glm|solar|kanana|exaone)\//i, '').trim(); }
export function checkModelStatus(model: string): [
    boolean,
    ModelInfo | undefined
] { const name = normalizeModelName(model); if (Object.hasOwn(CURRENT_MODELS, name))
    return [false, CURRENT_MODELS[name]]; if (Object.hasOwn(DEPRECATED_MODELS, name))
    return [true, DEPRECATED_MODELS[name]]; for (const [pattern, replacement, provider] of DEPRECATED_PATTERNS)
    if (pattern.test(name))
        return [true, { name, status: 'deprecated', provider, replacement }]; return [false, undefined]; }
export function getAllModelNames(): Set<string> { return new Set([...Object.keys(CURRENT_MODELS), ...Object.keys(DEPRECATED_MODELS)]); }
